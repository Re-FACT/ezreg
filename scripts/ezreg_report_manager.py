# Constants
TASK_NAME_TAG = "task"
UPPER_BOUND_TAG = "upper_bound"
LOWER_BOUND_TAG = "lower_bound"


# Class of a report manager
class EzRegReportManager:
    def __init__(self):
        # Internal data
        self.__report_names_ = []
        self.__report_files_ = []
        self.__report_datas_ = []
        self.__report_stats_ = []
        self.__report_expect_failure_ = []
        # All the metrics extracted from reports.
        self.__metrics_ = [TASK_NAME_TAG]

        self.__error_count_ = 0

    def report_tasks(self):
        return len(self.__report_names_)

    def create_report_task(self, val, expect_failure):
        idx = len(self.__report_names_)
        self.__report_names_.append(val)
        self.__report_files_.append("")
        self.__report_datas_.append({})
        self.__report_stats_.append({})
        self.__report_expect_failure_.append(expect_failure)
        return idx

    def add_report_file_to_task(self, task_idx, ftype, fpath, fmetric):
        self.__report_files_[task_idx] = [ftype, fpath, fmetric]

    # Parse all the reports and summarize stats
    def parse(self):
        for irpt in range(len(self.__report_names_)):
            if self.__report_expect_failure_[irpt]:
                continue
            elif not os.path.isfile(self.__report_files_[irpt][1]):
                raise Exception(
                    f"Report '{self.__report_files_[irpt][1]}' does not exist!\nFailed to parse the report!"
                )
            if self.__report_files_[irpt][0] == "json":
                self.__parse_report_json__(irpt)

    def __get_json_value_by_path(self, task_idx, kw_path):
        """
        Traverses a nested JSON (dictionary) using a slash-separated path string.
        Example path: 'design/num_cells_by_type/$lut'[cite: 3]
        """
        keys = kw_path.split("/")
        current = self.__report_datas_[task_idx]

        for key in keys:
            if isinstance(current, dict) and key in current:
                current = current[key]
            else:
                return None  # Key not found or intermediate node is not a dictionary

        return current

    # Parse the stat report generated by Yosys
    def __parse_report_json__(self, task_idx):
        self.__report_datas_[task_idx] = {}  # Ensure a clean start
        with open(self.__report_files_[task_idx][1], encoding="utf-8", mode="r") as frpt:
            try:
                self.__report_datas_[task_idx] = json.load(frpt)
            except json.JSONDecodeError as exc:
                logging.error(f"Invalid JSON syntax: {exc}")
        json_kws = ezreg_qor_json_keywords.EzRegQorJsonKeywords(self.__report_files_[task_idx][2])
        # Add records to stats
        self.__report_stats_[task_idx] = {}  # Ensure a clean start
        self.__report_stats_[task_idx][TASK_NAME_TAG] = self.__report_names_[task_idx]
        # For all the data, load each of them
        for imetric in json_kws.metrics():
            metric_name = json_kws.metric_name(imetric)
            metric_kw = json_kws.keyword(imetric)
            extract_val = self.__get_json_value_by_path(task_idx, metric_kw)
            if extract_val is None:
                raise Exception(
                    f"Expected metric '{metric_name}' cannot not be extracted. Please check if the keyword '{metric_kw}' is valid"
                )
            self.__report_stats_[task_idx][metric_name] = extract_val
            if metric_name not in self.__metrics_:
                self.__metrics_.append(metric_name)

    # Write report to file
    def write_stat_to_csv(self, csv_file, task_filter=""):
        # Create directories if does not exist
        if os.path.dirname(csv_file):
            os.makedirs(os.path.dirname(csv_file), exist_ok=True)
        with open(csv_file, "w") as csvf:
            spamwriter = csv.writer(csvf, delimiter=",", quotechar="|", quoting=csv.QUOTE_MINIMAL)
            # Add a head row
            spamwriter.writerow(self.__metrics_)
            # Add stat design by design
            for task_name in self.__report_names_:
                if task_filter and not task_name.startswith(task_filter):
                    continue
                curr_row = []
                curr_row.append(task_name)
                task_idx = self.__report_names_.index(task_name)
                for curr_metric in self.__metrics_:
                    if curr_metric == TASK_NAME_TAG:
                        continue
                    if curr_metric not in self.__report_stats_[task_idx]:
                        curr_row.append("0")
                    else:
                        if isinstance(self.__report_stats_[task_idx][curr_metric], str):
                            curr_row.append(
                                str(self.__report_stats_[task_idx][curr_metric]).replace(",", " ")
                            )
                        else:
                            curr_row.append(self.__report_stats_[task_idx][curr_metric])
                spamwriter.writerow(curr_row)

    # Check qor with a given report under a set of tolerance
    def diff_stat(self, task_idx, ref_csv):
        # Counter on diff
        num_diff = 0
        # Read spreadsheet
        if not os.path.isfile(ref_csv):
            raise Exception(f"The csv '{ref_csv}' does not exist.")
        with open(ref_csv, mode="r") as js_f:
            reader = csv.DictReader(js_f)
            # Compare with internal data
            for row in reader:
                if TASK_NAME_TAG not in row:
                    raise Exception(
                        f"Required column '{TASK_NAME_TAG}' is not found in the reference csv. The csv '{ref_csv}' may be corrupted."
                    )
                # Found matched design name and then compare stats one by one
                curr_design = row[TASK_NAME_TAG]
                if row[TASK_NAME_TAG] not in self.__report_names_:
                    raise Exception(
                        f"Design '{row[TASK_NAME_TAG]}' is not found in current run!\nPlease double check your reference csv '{ref_csv}'!"
                    )
                # Get the index and start diff
                task_idx = self.__report_names_.index(curr_design)
                # Build tolerance dict
                curr_tolrns = {}
                if self.__report_files_[task_idx][0] == "json":
                    json_kws = EzRegQorJsonKeywords(self.__report_files_[task_idx][2])
                    for ikw in json_kws.metrics():
                        curr_tolrns[json_kws.metric_name(ikw)][UPPER_BOUND_TAG] = (
                            json_kws.upper_bound(ikw)
                        )
                        curr_tolrns[json_kws.metric_name(ikw)][LOWER_BOUND_TAG] = (
                            json_kws.lower_bound(ikw)
                        )
                if len(curr_tolrns) == 0:
                    logging.info(f"No QoR check is required for design '{curr_design}'")
                for curr_metric in curr_tolrns.keys():
                    if curr_metric not in row:
                        raise Exception(f"Metric '{curr_metric}' is not found in the reference csv")
                    if curr_metric not in self.__metrics_:
                        raise Exception(f"Metric '{curr_metric}' is not found in the current run")
                    # Fill empty data
                    ref_val = 0
                    if curr_metric in self.__report_stats_[task_idx]:
                        ref_val = self.__report_stats_[task_idx][curr_metric]
                    # Now check upper bound
                    if (
                        float(row[curr_metric])
                        * (1.0 + float(curr_tolrns[curr_metric][UPPER_BOUND_TAG]))
                        < ref_val
                    ):
                        logging.info(
                            f"'{curr_metric}' of design '{curr_design}' in current run ({ref_val}) exceeds the upper bound limit {curr_tolrns[curr_metric][UPPER_BOUND_TAG]} (reference value is {row[curr_metric]})"
                        )
                        num_diff += 1
                    # Now check lower bound
                    if (
                        float(row[curr_metric])
                        * (1.0 - float(curr_tolrns[curr_metric][LOWER_BOUND_TAG]))
                        > ref_val
                    ):
                        logging.info(
                            f"'{curr_metric}' of design '{curr_design}' in current run ({ref_val}) exceeds the lower bound limit {curr_tolrns[curr_metric][LOWER_BOUND_TAG]} (reference value is {row[curr_metric]})"
                        )
                        num_diff += 1

        return num_diff

    # Clear all the data
    def clear(self):
        self.__init__()
